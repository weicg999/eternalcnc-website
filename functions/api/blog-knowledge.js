// ============================================================
// 关键词检索（粗召回 + 模型精筛）
// 定位：FAQ 秒答已拦截高频精确问题，本函数只负责"软性观点/文化/策略"兜底。
// 英文走单词命中，中文走 tags 命中 + 2 字滑窗命中（权重低于 tags）。
// 返回拼接好的 top-K 条目文本（zh 或 en），未命中返回空串。
// ============================================================
export function retrieveKnowledge(query, lang, topK = 3) {
  const q = String(query || '').trim();
  if (!q) return '';
  const ql = q.toLowerCase();
  const enWords = (ql.match(/[a-z][a-z0-9-]{2,}/g) || []);
  const scored = [];

  for (const item of blogKnowledge) {
    const zh = (item.title.zh + ' ' + item.description.zh).toLowerCase();
    const en = (item.title.en + ' ' + item.description.en + ' ' + (item.tags || []).join(' ')).toLowerCase();
    let score = 0;

    // 英文单词命中
    for (const w of enWords) {
      if (w.length >= 3 && en.includes(w)) score += (w.length >= 5 ? 3 : 2);
    }
    // 中文 tags 命中（作者提炼的关键词，权重最高）
    for (const t of (item.tags || [])) {
      if (/[\u4e00-\u9fa5]/.test(t) && q.includes(t)) score += (t.length >= 3 ? 4 : 3);
    }
    // 中文 2 字滑窗命中（弱召回，权重低）
    const segs = ql.match(/[\u4e00-\u9fa5]{2,}/g) || [];
    for (const s of segs) {
      for (let i = 0; i + 2 <= s.length; i++) {
        if (zh.includes(s.slice(i, i + 2))) score += 1;
      }
    }

    if (score > 0) scored.push({ item, score });
  }

  scored.sort((a, b) => b.score - a.score);
  const top = scored.slice(0, topK);
  if (!top.length) return '';

  return top.map((x) => (lang === 'zh'
    ? `·《${x.item.title.zh}》：${x.item.description.zh}`
    : `· "${x.item.title.en}": ${x.item.description.en}`)).join('\n');
}
